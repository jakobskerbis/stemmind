export function findPersonas(spec = "all") {
  if (!spec || spec === "all") return PERSONAS;
  const ids = String(spec)
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  const out = ids.map((id) => PERSONAS.find((p) => p.id === id || p.id.startsWith(id)));
  const missing = ids.filter((_, i) => !out[i]);
  if (missing.length) throw new Error(`Neznan učenec: ${missing.join(", ")}. Na voljo: ${PERSONAS.map((p) => p.id).join(", ")}`);
  return out;
}
